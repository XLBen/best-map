export function Help() {
  if (!helpOpen.value) return null;
  return (
    <div class="modal-backdrop" onClick={() => (helpOpen.value = false)}>
      <div class="modal help" onClick={(e) => e.stopPropagation()}>
        <ModalHead title="上手说明" onClose={() => (helpOpen.value = false)} />
        <ol class="steps">
          {STEPS.map(([title, items]) => (
            <li>
              <b>{title}</b>
              <ul>
                {items.map((t) => (
                  <li>{t}</li>
                ))}
              </ul>
            </li>
          ))}
        </ol>
        <h5>按键</h5>
        <table class="kv">
          <tbody>
            {KEYS.map(([k, v]) => (
              <tr>
                <th>{k}</th>
                <td>{v}</td>
              </tr>
            ))}
          </tbody>
        </table>
        <p class="hint">同样的操作，结果一样；想要别的样子点“换一个”</p>
      </div>
    </div>
  );
}
