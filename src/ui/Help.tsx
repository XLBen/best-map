export function Help() {
  if (!helpOpen.value) return null;
  return (
    <div class="modal-backdrop" onClick={() => (helpOpen.value = false)}>
      <div class="modal help" onClick={(e) => e.stopPropagation()}>
        <div class="row between">
          <h2>怎么用</h2>
          <button onClick={() => (helpOpen.value = false)}>知道了</button>
        </div>
        <ol class="steps">
          {STEPS.map(([title, text]) => (
            <li>
              <b>{title}</b>
              <p>{text}</p>
            </li>
          ))}
        </ol>
        <h4>操作</h4>
        <table class="kv">
          <tbody>
            {KEYS.map(([k, v]) => (
              <tr>
                <th>{k}</th>
                <td>{v}</td>
              </tr>
            ))}
          </tbody>
        </table>
        <p class="muted small">
          同样的操作做两遍，结果一样：放岛时悬停看到的轮廓就是放下去的岛，放下一个后自动换下一个形状（岛链也自动换下一种排列）。想要别的样子，就点“换一组”“换一种划分”“换一个”这类按钮。
        </p>
      </div>
    </div>
  );
}
